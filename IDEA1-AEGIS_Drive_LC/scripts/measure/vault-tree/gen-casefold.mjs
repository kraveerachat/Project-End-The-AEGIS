// scripts/measure/vault-tree/gen-casefold.mjs — PR #157 Task 1.4 · generator for src/lib/unicodeCaseFold.js
//
// Reads a pinned Unicode CaseFolding.txt (statuses C + F = full case folding) and
// emits the mapping table module. The source file is NOT committed (Unicode
// license/terms); its version and SHA-256 are recorded in the generated header so
// the table is reproducible and pinned.
//
//   node scripts/measure/vault-tree/gen-casefold.mjs --in <CaseFolding.txt> --version 16.0.0 --out src/lib/unicodeCaseFold.js
import fs from 'node:fs'
import { createHash } from 'node:crypto'

const args = process.argv.slice(2)
const opt = (n) => { const i = args.indexOf(n); return i >= 0 ? args[i + 1] : null }
const inPath = opt('--in'), version = opt('--version'), outPath = opt('--out')
if (!inPath || !version || !outPath) { console.error('need --in --version --out'); process.exit(2) }

const raw = fs.readFileSync(inPath)
const sha256 = createHash('sha256').update(raw).digest('hex')
const text = raw.toString('utf8')
const entries = []
for (const line of text.split('\n')) {
  const l = line.split('#')[0].trim()
  if (!l) continue
  const [code, status, mapping] = l.split(';').map((s) => s.trim())
  if (status !== 'C' && status !== 'F') continue // S = simple-only alternatives, T = Turkic special-casing: excluded
  const from = parseInt(code, 16)
  const to = mapping.split(/\s+/).map((h) => parseInt(h, 16))
  entries.push([from, to])
}
entries.sort((a, b) => a[0] - b[0])
// compact: "hex:hex hex" pairs joined by ';'
const packed = entries.map(([f, t]) => f.toString(16) + ':' + t.map((c) => c.toString(16)).join(' ')).join(';')
const out = `// src/lib/unicodeCaseFold.js — AEGIS Drive (IDEA1) · Private Vault encrypted hierarchy · pinned full case folding
//
// GENERATED by scripts/measure/vault-tree/gen-casefold.mjs — do not edit by hand.
//   source: CaseFolding.txt, Unicode ${version}
//   sha256: ${sha256}
//   statuses: C + F (full case folding); S and T excluded
//   entries: ${entries.length}
//
// ⚠️ นี่คือส่วนหนึ่งของ "นโยบายชื่อชนกัน" ของ manifest (design §13): collision key = NFC → full case
//    folding ด้วยตารางนี้ "ที่ตรึงเวอร์ชันไว้" — ไม่ใช่ String.prototype.toLowerCase ของเบราว์เซอร์ที่
//    เปลี่ยนตาม runtime การเปลี่ยนตารางต้องเป็นการเปลี่ยนเวอร์ชันของนโยบาย ไม่ใช่การอัปเดตเงียบ ๆ

export const CASE_FOLD_UNICODE_VERSION = ${JSON.stringify(version)}
export const CASE_FOLD_SOURCE_SHA256 = ${JSON.stringify(sha256)}

const PACKED = ${JSON.stringify(packed)}

/** @type {Map<number, string>} code point → folded string */
export const CASE_FOLD_MAP = new Map(PACKED.split(';').map((e) => {
  const [from, to] = e.split(':')
  return [parseInt(from, 16), String.fromCodePoint(...to.split(' ').map((h) => parseInt(h, 16)))]
}))

/** full case folding (C+F) ของสตริงตามตารางที่ตรึงไว้ — ไม่ normalize; ผู้เรียกทำ NFC ก่อน */
export function caseFold(s) {
  let out = ''
  for (const ch of s) {
    const cp = ch.codePointAt(0)
    const m = CASE_FOLD_MAP.get(cp)
    out += m === undefined ? ch : m
  }
  return out
}
`
fs.writeFileSync(outPath, out)
console.log(`wrote ${outPath}: ${entries.length} entries, Unicode ${version}, sha256 ${sha256}`)
