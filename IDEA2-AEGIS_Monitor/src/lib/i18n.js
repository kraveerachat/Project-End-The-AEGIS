export function translate(lang, message, params = {}) {
  const entry = Object.hasOwn(messages, message) ? messages[message] : null
  const selected = normalizeLanguage(lang)
  const template = selected === 'en' || !entry ? message : entry[selected === 'th' ? 0 : 1]
  // Values are literal React text, never recursively translated or HTML.
  return String(template ?? message).replace(/\{([a-zA-Z][a-zA-Z0-9]*)\}/g,
    (token, key) => Object.hasOwn(params, key) ? String(params[key]) : token)
}
