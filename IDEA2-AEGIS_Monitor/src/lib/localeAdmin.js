// Render-time allowlist only: unknown server details retain their exact content.
export function adminErrorMessage(error, t) {
  if (knownAdminErrors.has(error)) return t(error)
  const unknownCamera = /^Unknown camera: (CAM-[A-Z0-9-]+)$/.exec(error)
  if (unknownCamera) return t('Unknown camera: {camera}', { camera: unknownCamera[1] })
  const assignedCamera = /^Camera (CAM-[A-Z0-9-]+) is already assigned to an operator$/.exec(error)
  if (assignedCamera) return t('Camera {camera} is already assigned to an operator', { camera: assignedCamera[1] })
  return error
}
