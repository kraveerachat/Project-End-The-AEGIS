export function normalizeLanguage(value) {
  return LANGS.includes(value) ? value : 'th'
}

export function localeFor(language) {
  return localeByLanguage[normalizeLanguage(language)]
}

export function htmlLanguage(language) {
  return htmlLanguageByLanguage[normalizeLanguage(language)]
}

export function makeT(language) {
  const table = STRINGS[normalizeLanguage(language)]
  return (key, variables = {}) => {
    if (!Object.hasOwn(table, key)) return key
    return Object.entries(variables).reduce(
      (copy, [name, value]) => copy.replaceAll(`{${name}}`, String(value)),
      table[key],
    )
  }
}

export function statusLabel(status, language) {
  return makeT(language)(statusKeys[status] || statusKeys.UNKNOWN)
}
